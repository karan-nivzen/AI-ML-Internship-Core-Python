# Arithmetic
print(2 + 3)
print(7 - 4)
print(3 * 4)
print(12 / 4)

# Operator precedence
print(2 + 3 * 4)
print((2 + 3) * 4)

# Exponentiation (**), not XOR (^)
print(2 ** 3)

# The three division operators
print(7 / 2)
print(7 // 2)
print(7 % 2)

